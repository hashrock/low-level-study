package minicc

import (
	"fmt"
	"sort"
	"strings"
)

// AST → RISC-V アセンブリ。
//
// 方針 (わかりやすさ優先):
//   - 式の結果は常に a0 に置く。
//   - 途中結果 (二項演算の左辺、引数など) はフレーム内の「一時スロット」に退避する。
//     sp を動かす push/pop の代わりに、深さごとに決まったオフセットを使うので
//     sp は関数の中で一度も動かない (16 バイト境界も自動的に保たれる)。
//   - 型検査が必要な演算は runtime.s の rt_* を呼ぶ。整数どうしの + - * < などは
//     インラインの「速い道」を出す。
//
// スタックフレーム (fp = s0 = 関数に入ったときの sp):
//
//	fp-8    ra (戻りアドレス)
//	fp-16   呼び出し元の fp
//	fp-24   自分のクロージャ (環境: 捕捉した箱へのポインタ配列を持つ)
//	fp-32   スロット 0 (引数・ローカル変数)
//	 ...
//	        一時スロット 0, 1, ...
//	sp      (16 バイト境界)

const (
	frameHeader = 24 // ra, 旧 fp, クロージャ
	closureFree = 40 // クロージャ object 内で箱ポインタが始まるオフセット
)

type site struct {
	label string
	pos   Pos
}

type loopLabels struct{ cont, brk string }

type Gen struct {
	r        *Resolver
	src      []string
	text     strings.Builder
	data     strings.Builder
	rodata   strings.Builder
	strs     map[string]string
	sites    []site
	nlabel   int
	fn       *FuncInfo
	body     *strings.Builder
	depth    int
	maxDepth int
	loops    []loopLabels
	ret      string
	lastLine int
}

func Generate(prog []Stmt, src string) (out string, err error) {
	out, _, err = generate(prog, src)
	return out, err
}

// generate は Generate と同じだが、関数ラベル → 関数リテラルの行 の対応も返す。
func generate(prog []Stmt, src string) (out string, fnLines map[string]int, err error) {
	r, err := Resolve(prog)
	if err != nil {
		return "", nil, err
	}
	defer func() {
		if e := recover(); e != nil {
			le, ok := e.(*LangError)
			if !ok {
				panic(e)
			}
			err = le
		}
	}()
	g := &Gen{r: r, src: strings.Split(src, "\n"), strs: map[string]string{}}
	g.text.WriteString("# generated by minicc\n" +
		"\t.equ NIL, 2\n\t.equ FALSE, 4\n\t.equ TRUE, 6\n\n\t.text\n\t.globl mini_main\n")
	g.data.WriteString("\n\t.data\n\t.balign 8\n")
	g.rodata.WriteString("\n\t.rodata\n")

	// グローバル変数 (名前順で安定させる)
	var names []string
	for n := range r.topNames {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&g.data, "g_%s:\t.dword NIL\n", n)
	}
	// 関数本体を順に出力 (トップレベル → 出現順の関数リテラル)
	for _, f := range r.all {
		if f.Lit == nil {
			g.function(f, nil, prog)
		} else {
			g.function(f, f.Lit.Params, f.Lit.Body)
		}
	}
	// 実行時エラーの位置表: 「rt_* 呼び出しの戻り番地 → 行, 列」
	g.rodata.WriteString("\t.balign 8\n\t.globl mini_sites\nmini_sites:\n")
	for _, s := range g.sites {
		fmt.Fprintf(&g.rodata, "\t.dword %s, %d, %d\n", s.label, s.pos.Line, s.pos.Col)
	}
	g.rodata.WriteString("\t.dword 0\n")
	fnLines = map[string]int{}
	for _, f := range r.all {
		if f.Lit != nil {
			fnLines[f.Label] = f.Lit.Pos().Line
		}
	}
	return g.text.String() + g.data.String() + g.rodata.String(), fnLines, nil
}

// ---- 出力の小道具 ----

func (g *Gen) label(kind string) string { g.nlabel++; return fmt.Sprintf(".L%s_%d", kind, g.nlabel) }
func (g *Gen) emit(format string, args ...any) {
	line := fmt.Sprintf(format, args...)
	if i := strings.Index(line, "#"); i > 0 { // コメントの桁を揃える
		line = fmt.Sprintf("%-24s %s", strings.TrimRight(line[:i], " "), line[i:])
	}
	fmt.Fprintf(g.body, "\t%s\n", line)
}
func (g *Gen) emitLabel(l string) { fmt.Fprintf(g.body, "%s:\n", l) }

// callRT はランタイム関数を呼び、戻り番地にラベルを付けて位置表に登録する。
func (g *Gen) callRT(fn string, p Pos) {
	g.emit("call %s", fn)
	g.site(p)
}
func (g *Gen) site(p Pos) {
	l := g.label("site")
	g.emitLabel(l)
	g.sites = append(g.sites, site{l, p})
}

// 一時スロット: push で a0 を退避、pop で取り出す
func (g *Gen) tempOff(i int) int { return -(frameHeader + 8*(g.fn.NumSlots+i) + 8) }
func (g *Gen) slotOff(s int) int { return -(frameHeader + 8*s + 8) }
func (g *Gen) push() int {
	g.emit("sd a0, %d(fp)", g.tempOff(g.depth))
	g.depth++
	g.maxDepth = max(g.maxDepth, g.depth)
	return g.depth - 1
}
func (g *Gen) pop(reg string) {
	g.depth--
	g.emit("ld %s, %d(fp)", reg, g.tempOff(g.depth))
}

func (g *Gen) str(s string) string {
	if l, ok := g.strs[s]; ok {
		return l
	}
	l := fmt.Sprintf(".Lstr_%d", len(g.strs))
	g.strs[s] = l
	// 文字列 object: [型タグ 1][長さ][バイト列]  (静的に置くのでヒープ割り当て不要)
	fmt.Fprintf(&g.rodata, "\t.balign 8\n%s:\t.dword 1, %d\n", l, len(s))
	if s != "" {
		fmt.Fprintf(&g.rodata, "\t.ascii \"%s\"\n", escapeAsm(s))
	}
	return l
}

func escapeAsm(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\x%02x", c)
		}
	}
	return b.String()
}

// ソース行をコメントとして出す (同じ行は 1 度だけ)
func (g *Gen) comment(p Pos) {
	if p.Line == g.lastLine || p.Line < 1 || p.Line > len(g.src) {
		return
	}
	g.lastLine = p.Line
	fmt.Fprintf(g.body, "\t# %d: %s\n", p.Line, strings.TrimSpace(g.src[p.Line-1]))
}

// ---- 関数 ----

func (g *Gen) function(f *FuncInfo, params []string, body []Stmt) {
	var b strings.Builder
	g.fn, g.body, g.depth, g.maxDepth, g.loops, g.lastLine = f, &b, 0, 0, nil, 0
	g.ret = g.label("ret")
	// 引数 a1..a7 をスロットへ (a0 は自分のクロージャ)
	g.emit("sd a0, -24(fp)      # 自分のクロージャ (環境)")
	for i, v := range f.Params {
		g.emit("sd a%d, %d(fp)      # 引数 %s", i+1, g.slotOff(v.Slot), v.Name)
	}
	for _, v := range f.Params {
		if v.Captured { // 捕捉される引数は箱に移す
			g.emit("ld a0, %d(fp)", g.slotOff(v.Slot))
			g.emit("call rt_box         # %s は捕捉されるので箱に入れる", v.Name)
			g.emit("sd a0, %d(fp)", g.slotOff(v.Slot))
		}
	}
	g.stmts(body)
	g.emit("li a0, NIL")
	g.emitLabel(g.ret)

	size := (frameHeader + 8*(f.NumSlots+g.maxDepth) + 15) &^ 15
	if size > 2032 {
		compileErr(Pos{}, "function %s needs too large a frame (%d bytes)", f.Name, size)
	}
	t := &g.text
	sig := f.Name
	if f.Lit != nil {
		sig += "(" + strings.Join(params, ", ") + ")"
		if len(f.Free) > 0 {
			var fv []string
			for _, v := range f.Free {
				fv = append(fv, v.Name)
			}
			sig += "  捕捉: " + strings.Join(fv, ", ")
		}
	}
	fmt.Fprintf(t, "\n# ---- %s  (フレーム %d バイト: スロット %d + 一時 %d)\n", sig, size, f.NumSlots, g.maxDepth)
	fmt.Fprintf(t, "%s:\n", f.Label)
	fmt.Fprintf(t, "\taddi sp, sp, -%d\n\tsd ra, %d(sp)\n\tsd fp, %d(sp)\n\taddi fp, sp, %d\n",
		size, size-8, size-16, size)
	ok := g.label("stack_ok") // Go のように入口でスタックの残りを確認する
	fmt.Fprintf(t, "\tla t0, rt_stack_limit\n\tld t0, 0(t0)\n\tbgeu sp, t0, %s\n\tcall rt_stack_overflow\n%s:\n", ok, ok)
	t.WriteString(b.String())
	fmt.Fprintf(t, "\tld ra, %d(sp)\n\tld fp, %d(sp)\n\taddi sp, sp, %d\n\tret\n", size-8, size-16, size)
}

// ---- 変数アクセス ----

// loadVar は変数の値を a0 に読む。
func (g *Gen) loadVar(v *Var) {
	switch {
	case v.Builtin:
		g.emit("la a0, rt_fn_%s      # 組み込み関数 %s を値として使う", v.Name, v.Name)
	case v.Global:
		g.emit("la t0, g_%s", v.Name)
		g.emit("ld a0, 0(t0)        # グローバル %s", v.Name)
	default:
		g.boxOrSlot(v, "a0")
		if v.Captured {
			g.emit("ld a0, 0(a0)        # 箱の中身")
		}
	}
}

// storeVar は a0 を変数に書く (a0 は壊さない)。
func (g *Gen) storeVar(v *Var) {
	switch {
	case v.Global:
		g.emit("la t0, g_%s", v.Name)
		g.emit("sd a0, 0(t0)        # グローバル %s", v.Name)
	case v.Captured:
		g.boxOrSlot(v, "t0")
		g.emit("sd a0, 0(t0)        # 箱に書く")
	default:
		g.emit("sd a0, %d(fp)       # %s", g.slotOff(v.Slot), v.Name)
	}
}

// boxOrSlot は自分のスロットの中身、または捕捉した箱のポインタを reg に読む。
func (g *Gen) boxOrSlot(v *Var, reg string) {
	if v.Fn == g.fn {
		g.emit("ld %s, %d(fp)       # %s", reg, g.slotOff(v.Slot), v.Name)
		return
	}
	g.emit("ld t1, -24(fp)       # 環境 (クロージャ)")
	g.emit("ld %s, %d(t1)        # 捕捉した %s の箱", reg, closureFree+8*g.fn.freeIndex(v), v.Name)
}

// define は宣言 (let / 引数以外) の初期化。値は a0。
func (g *Gen) define(v *Var) {
	if v.Captured && !v.Global {
		g.emit("call rt_box         # 捕捉される変数は新しい箱に入れる")
		g.emit("sd a0, %d(fp)       # %s (箱)", g.slotOff(v.Slot), v.Name)
		return
	}
	g.storeVar(v)
}

// ---- 文 ----

func (g *Gen) stmts(list []Stmt) {
	for _, s := range list {
		g.stmt(s)
	}
}

func (g *Gen) stmt(s Stmt) {
	g.comment(s.Pos())
	switch s := s.(type) {
	case *LetStmt:
		v := g.r.decl[s]
		if s.IsFn && v.Captured { // 再帰する局所関数: 先に空の箱を作る
			g.emit("li a0, NIL")
			g.define(v)
			g.expr(s.Value)
			g.storeVar(v)
		} else {
			g.expr(s.Value)
			g.define(v)
		}
	case *ExprStmt:
		g.expr(s.X)
	case *BlockStmt:
		g.stmts(s.Body)
	case *IfStmt:
		elseL, endL := g.label("else"), g.label("endif")
		g.cond(s.Cond, elseL)
		g.stmts(s.Then)
		if s.Else != nil {
			g.emit("j %s", endL)
		}
		g.emitLabel(elseL)
		if s.Else != nil {
			g.stmt(s.Else)
			g.emitLabel(endL)
		}
	case *WhileStmt:
		top, end := g.label("while"), g.label("endwhile")
		g.emitLabel(top)
		g.cond(s.Cond, end)
		g.loop(top, end, s.Body)
		g.emit("j %s", top)
		g.emitLabel(end)
	case *ForInStmt:
		g.forIn(s)
	case *ReturnStmt:
		if s.Value != nil {
			g.expr(s.Value)
		} else {
			g.emit("li a0, NIL")
		}
		g.emit("j %s", g.ret)
	case *BreakStmt, *ContinueStmt:
		if len(g.loops) == 0 {
			compileErr(s.Pos(), "break/continue outside loop")
		}
		l := g.loops[len(g.loops)-1]
		if _, ok := s.(*BreakStmt); ok {
			g.emit("j %s", l.brk)
		} else {
			g.emit("j %s", l.cont)
		}
	}
}

func (g *Gen) loop(cont, brk string, body []Stmt) {
	g.loops = append(g.loops, loopLabels{cont, brk})
	g.stmts(body)
	g.loops = g.loops[:len(g.loops)-1]
}

// for (x in xs) { body }
//
//	c = rt_iter(xs)   ; 配列はそのまま、マップはキーの配列
//	i = 0             ; 生の整数 (タグなし)
//	loop: if i >= c.len goto end ; x = c.buf[i] ; i++ ; body ; goto loop
func (g *Gen) forIn(s *ForInStmt) {
	sl := g.r.forSlots[s]
	c, i := g.slotOff(sl[0]), g.slotOff(sl[1])
	top, end := g.label("for"), g.label("endfor")
	g.expr(s.Iter)
	g.callRT("rt_iter", s.Iter.Pos())
	g.emit("sd a0, %d(fp)       # 隠しスロット: 反復対象の配列", c)
	g.emit("sd zero, %d(fp)     # 隠しスロット: 添字 (生の整数)", i)
	g.emitLabel(top)
	g.emit("ld t0, %d(fp)", c)
	g.emit("ld t1, %d(fp)", i)
	g.emit("ld t2, 8(t0)         # 配列の長さ")
	g.emit("bge t1, t2, %s", end)
	g.emit("ld t3, 24(t0)        # 要素バッファ")
	g.emit("slli t4, t1, 3")
	g.emit("add t3, t3, t4")
	g.emit("ld a0, 0(t3)         # 要素 i")
	g.emit("addi t1, t1, 1")
	g.emit("sd t1, %d(fp)", i)
	g.define(g.r.decl[s]) // 捕捉されるなら反復ごとに新しい箱
	g.loop(top, end, s.Body)
	g.emit("j %s", top)
	g.emitLabel(end)
}

// cond は式を評価し、偽 (false か nil) なら falseL へ飛ぶ。
func (g *Gen) cond(e Expr, falseL string) {
	g.expr(e)
	g.emit("li t0, FALSE")
	g.emit("beq a0, t0, %s", falseL)
	g.emit("li t0, NIL")
	g.emit("beq a0, t0, %s", falseL)
}

// ---- 式 ----

func (g *Gen) expr(e Expr) {
	switch e := e.(type) {
	case *NumberLit:
		g.emit("li a0, %d           # 数値 %d (タグ付き: 2n+1)", int64(e.V)*2+1, int64(e.V))
	case *StringLit:
		g.emit("la a0, %s", g.str(e.V))
	case *BoolLit:
		if e.V {
			g.emit("li a0, TRUE")
		} else {
			g.emit("li a0, FALSE")
		}
	case *NilLit:
		g.emit("li a0, NIL")
	case *Ident:
		g.loadVar(g.r.uses[e])
	case *ArrayLit:
		g.emit("li a0, %d", len(e.Elems))
		g.emit("call rt_array_new")
		arr := g.push()
		for _, x := range e.Elems {
			g.expr(x)
			g.emit("mv a1, a0")
			g.emit("ld a0, %d(fp)", g.tempOff(arr))
			g.emit("call rt_push")
		}
		g.pop("a0")
	case *MapLit:
		g.emit("call rt_map_new")
		m := g.push()
		for i, k := range e.Keys {
			g.expr(e.Vals[i])
			g.emit("mv a2, a0")
			g.emit("la a1, %s", g.str(k))
			g.emit("ld a0, %d(fp)", g.tempOff(m))
			g.emit("call rt_setindex")
		}
		g.pop("a0")
	case *Unary:
		g.expr(e.X)
		if e.Op == "-" {
			g.callRT("rt_neg", e.P)
		} else { // !x: 偽なら TRUE、真なら FALSE
			yes, done := g.label("not_true"), g.label("not_done")
			g.emit("li t0, FALSE")
			g.emit("beq a0, t0, %s", yes)
			g.emit("li t0, NIL")
			g.emit("beq a0, t0, %s", yes)
			g.emit("li a0, FALSE")
			g.emit("j %s", done)
			g.emitLabel(yes)
			g.emit("li a0, TRUE")
			g.emitLabel(done)
		}
	case *Binary:
		g.binary(e)
	case *Assign:
		g.assign(e)
	case *Index:
		g.expr(e.X)
		g.push()
		g.expr(e.Key)
		g.emit("mv a1, a0")
		g.pop("a0")
		g.callRT("rt_index", e.P)
	case *Call:
		g.call(e)
	case *FuncLit:
		g.closure(g.r.funcs[e])
	}
}

func (g *Gen) assign(e *Assign) {
	if id, ok := e.Target.(*Ident); ok {
		g.expr(e.Value)
		g.storeVar(g.r.uses[id])
		return
	}
	ix := e.Target.(*Index)
	g.expr(ix.X)
	g.push()
	g.expr(ix.Key)
	g.push()
	g.expr(e.Value)
	g.emit("mv a2, a0")
	g.pop("a1")
	g.pop("a0")
	g.callRT("rt_setindex", e.P)
}

// closure はクロージャ object を作る: [タグ 4][コード][引数の数][名前][捕捉数][箱...]
func (g *Gen) closure(f *FuncInfo) {
	if len(f.Free) == 0 { // 何も捕捉しない関数はクロージャを静的に置ける
		l := "clo_" + f.Label
		fmt.Fprintf(&g.data, "%s:\t.dword 4, %s, %d, %s, 0\n", l, f.Label, len(f.Params), g.str(f.Name))
		g.emit("la a0, %s     # 捕捉なし → 静的なクロージャ", l)
		return
	}
	g.emit("li a0, %d", len(f.Free))
	g.emit("la a1, %s", f.Label)
	g.emit("li a2, %d", len(f.Params))
	g.emit("la a3, %s", g.str(f.Name))
	g.emit("call rt_closure_new")
	for i, v := range f.Free { // 箱のポインタをコピー (値ではなく箱を共有する)
		g.boxOrSlot(v, "t0")
		g.emit("sd t0, %d(a0)        # 捕捉 %s", closureFree+8*i, v.Name)
	}
}

func (g *Gen) call(e *Call) {
	if id, ok := e.Fn.(*Ident); ok && g.r.uses[id].Builtin {
		g.builtinCall(id.Name, e)
		return
	}
	base := g.depth
	g.expr(e.Fn)
	g.push()
	for _, a := range e.Args {
		g.expr(a)
		g.push()
	}
	g.emit("ld a0, %d(fp)", g.tempOff(base))
	g.emit("li a1, %d", len(e.Args))
	g.callRT("rt_checkcall", e.P) // 関数か? 引数の数は合うか?
	for i := range e.Args {
		g.emit("ld a%d, %d(fp)", i+1, g.tempOff(base+1+i))
	}
	g.emit("ld t0, 8(a0)         # コードのアドレス")
	g.emit("jalr t0              # 呼び出し: a0=クロージャ, a1..=引数")
	g.site(e.P)
	g.depth = base
}

func (g *Gen) builtinCall(name string, e *Call) {
	n := len(e.Args)
	if want := builtinArity[name]; want >= 0 && want != n ||
		name == "range" && (n < 1 || n > 2) {
		compileErr(e.P, "%s: wrong number of arguments (%d)", name, n)
	}
	base := g.depth
	for _, a := range e.Args {
		g.expr(a)
		g.push()
	}
	g.depth = base
	if name == "print" { // 全引数を評価してから 1 行を組み立てて出力
		for i := 0; i < n; i++ {
			if i > 0 {
				g.emit("call rt_print_sp")
			}
			g.emit("ld a0, %d(fp)", g.tempOff(base+i))
			g.emit("call rt_print_val")
		}
		g.emit("call rt_print_nl")
		return
	}
	if name == "range" && n == 1 {
		g.emit("li a0, 1             # range(n) = range(0, n)")
		g.emit("ld a1, %d(fp)", g.tempOff(base))
	} else {
		for i := 0; i < n; i++ {
			g.emit("ld a%d, %d(fp)", i, g.tempOff(base+i))
		}
	}
	g.callRT("rt_"+name, e.P)
}

var rtBinop = map[string]string{
	"+": "rt_add", "-": "rt_sub", "*": "rt_mul", "/": "rt_div", "%": "rt_mod",
	"<": "rt_lt", "<=": "rt_le", ">": "rt_gt", ">=": "rt_ge",
}

func (g *Gen) binary(e *Binary) {
	if e.Op == "&&" || e.Op == "||" { // 短絡評価: オペランドの値そのものを返す
		end := g.label("sc")
		g.expr(e.L)
		if e.Op == "&&" {
			g.emit("li t0, FALSE")
			g.emit("beq a0, t0, %s", end)
			g.emit("li t0, NIL")
			g.emit("beq a0, t0, %s", end)
		} else {
			rhs := g.label("or_rhs")
			g.emit("li t0, FALSE")
			g.emit("beq a0, t0, %s", rhs)
			g.emit("li t0, NIL")
			g.emit("beq a0, t0, %s", rhs)
			g.emit("j %s", end)
			g.emitLabel(rhs)
		}
		g.expr(e.R)
		g.emitLabel(end)
		return
	}
	g.expr(e.L)
	g.push()
	g.expr(e.R)
	g.emit("mv a1, a0")
	g.pop("a0")
	switch e.Op {
	case "==", "!=":
		g.emit("call rt_eq")
		if e.Op == "!=" {
			g.emit("xori a0, a0, 2       # TRUE(6) <-> FALSE(4)")
		}
		return
	case "/", "%":
		g.callRT(rtBinop[e.Op], e.P)
		return
	}
	// 整数どうしなら速い道 (両方の最下位ビットが 1)、そうでなければランタイムへ
	slow, done := g.label("slow"), g.label("done")
	g.emit("and t0, a0, a1")
	g.emit("andi t0, t0, 1")
	g.emit("beqz t0, %s        # どちらかが整数でない", slow)
	switch e.Op {
	case "+":
		g.emit("add a0, a0, a1")
		g.emit("addi a0, a0, -1      # (2a+1)+(2b+1)-1 = 2(a+b)+1")
	case "-":
		g.emit("sub a0, a0, a1")
		g.emit("addi a0, a0, 1       # (2a+1)-(2b+1)+1 = 2(a-b)+1")
	case "*":
		g.emit("srai t1, a1, 1       # b")
		g.emit("addi a0, a0, -1      # 2a")
		g.emit("mul a0, a0, t1")
		g.emit("addi a0, a0, 1       # 2ab+1")
	case "<":
		g.emit("slt t0, a0, a1       # タグ付きのままでも大小関係は同じ")
	case ">":
		g.emit("slt t0, a1, a0")
	case "<=":
		g.emit("slt t0, a1, a0")
		g.emit("xori t0, t0, 1")
	case ">=":
		g.emit("slt t0, a0, a1")
		g.emit("xori t0, t0, 1")
	}
	if strings.ContainsAny(e.Op[:1], "<>") {
		g.emit("slli t0, t0, 1")
		g.emit("addi a0, t0, FALSE   # 0/1 → FALSE(4)/TRUE(6)")
	}
	g.emit("j %s", done)
	g.emitLabel(slow)
	g.callRT(rtBinop[e.Op], e.P)
	g.emitLabel(done)
}
